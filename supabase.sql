create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text default '',
  file_name text not null,
  file_url text not null,
  file_type text not null check (file_type in ('image','video')),
  created_at timestamptz default now()
);

alter table public.admins enable row level security;

-- Allow an authenticated admin to see only their own admin-row; this is needed
-- by the EXISTS checks used by the write policies below.
create policy "admins can read own row"
on public.admins for select
to authenticated
using (user_id = auth.uid());
alter table public.site_content enable row level security;
alter table public.gallery enable row level security;

-- Public website can read content and gallery.
create policy "public can read site content"
on public.site_content for select
to anon, authenticated
using (true);

create policy "public can read gallery"
on public.gallery for select
to anon, authenticated
using (true);

-- Only the admin user listed in public.admins can edit content/gallery.
create policy "admin can update site content"
on public.site_content for update
to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admins a where a.user_id = auth.uid()));

create policy "admin can insert gallery"
on public.gallery for insert
to authenticated
with check (exists (select 1 from public.admins a where a.user_id = auth.uid()));

create policy "admin can delete gallery"
on public.gallery for delete
to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()));

