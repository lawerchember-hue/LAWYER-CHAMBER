-- Storage policies for the PUBLIC bucket named gallery.
-- Anyone can view public files; only the listed admin can upload/delete.
create policy "public can view gallery files"
on storage.objects for select
to public
using (bucket_id = 'gallery');

create policy "admin can upload gallery files"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'gallery'
  and exists (select 1 from public.admins a where a.user_id = auth.uid())
);

create policy "admin can delete gallery files"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'gallery'
  and exists (select 1 from public.admins a where a.user_id = auth.uid())
);
